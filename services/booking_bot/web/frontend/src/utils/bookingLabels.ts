// Названия шагов записи (настраиваются владельцем в «Настройках → Сценарий записи»).
// Общий код для страницы записи клиента и для предпросмотра в настройках.

// Винительный падеж для стандартных названий шагов («Выберите услугу»).
// Для кастомных названий бизнеса используем форму «Выберите: …».
export const ACCUSATIVE: Record<string, string> = {
  'услуга': 'услугу', 'мастер': 'мастера', 'специалист': 'специалиста', 'зал': 'зал',
  'дата': 'дату', 'время': 'время', 'доп. услуги': 'доп. услуги',
}

export function choosePhrase(verb: string, label: string) {
  const acc = ACCUSATIVE[label.trim().toLowerCase()]
  if (acc) return `${verb} ${acc}`
  // Своё название шага оставляем как есть, только с заглавной буквы.
  const custom = label.trim()
  return `${verb}: ${custom.charAt(0).toUpperCase()}${custom.slice(1)}`
}
